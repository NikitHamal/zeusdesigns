/** Merge preset endpoints into existing customProviders without overwriting saved API keys. */
export function mergeOpenCodeCustomProviders(existing: CustomProvider[] | undefined): CustomProvider[] {
  const list = Array.isArray(existing) ? existing.map((c) => ({ ...c })) : [];
  const byId = new Map(list.map((c) => [c.id, c]));
  const byBase = new Map(list.map((c) => [c.baseUrl.replace(/\/+$/, "").toLowerCase(), c]));
  for (const preset of OPENCODE_CUSTOM_PROVIDERS) {
    const baseKey = preset.baseUrl.replace(/\/+$/, "").toLowerCase();
    const hit = byId.get(preset.id) ?? byBase.get(baseKey);
    if (hit) {
      if (!hit.models?.length && preset.models?.length) hit.models = [...preset.models];
    } else {
      list.push({ ...preset, models: preset.models ? [...preset.models] : undefined });
    }
  }
  return list;
}
