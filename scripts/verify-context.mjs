// Probes live /models endpoints that publish real limits and writes src/lib/ctxVerified.ts.
// Run: node scripts/verify-context.mjs   (needs network; no keys)
import { writeFileSync } from "node:fs";
const get = async (url, headers = {}) => {
  try { const r = await fetch(url, { headers, signal: AbortSignal.timeout(25000) }); return r.ok ? await r.json() : null; } catch { return null; }
};
const out = {};
const kilo = await get("https://api.kilo.ai/api/gateway/models");
if (kilo) {
  out.kilo = {};
  for (const m of kilo.data ?? []) {
    if (!/free/.test(m.id) || !m.context_length) continue;
    out.kilo[m.id] = { ctx: m.context_length, out: m.top_provider?.max_completion_tokens ?? undefined, vision: (m.architecture?.input_modalities ?? []).includes("image"), reasoning: (m.supported_parameters ?? []).includes("reasoning") };
  }
}
const flh = await get("https://bun008-freellmapi.hf.space/v1/models");
if (flh) {
  out.freellmhub = {};
  for (const m of flh.data ?? []) { const c = m.context_window ?? m.context_length ?? m.max_model_len ?? m.contextWindow; if (c) out.freellmhub[m.id] = { ctx: c }; };
}
const zen = await get("https://opencode.ai/zen/v1/models", { Authorization: "Bearer public" });
if (zen) {
  out.opencodezen = {};
  for (const m of zen.data ?? []) {
    const free = JSON.stringify(m.cost ?? {}).match(/"price":(\d|\.)+/g)?.every((p) => p === '"price":0');
    if (!free || !m.limit?.context) continue;
    out.opencodezen[m.id] = { ctx: m.limit.context, out: m.limit.output ?? undefined, vision: (m.modalities?.input ?? []).some((x) => x.startsWith("image")), reasoning: !!m.capabilities?.reasoning?.supported, name: m.name };
  }
}
const body = `// Generated by scripts/verify-context.mjs from live gateway /models responses. Do not edit by hand.\nexport interface Verified { ctx: number; out?: number; vision?: boolean; reasoning?: boolean; name?: string }\nexport const CTX_VERIFIED: Record<string, Record<string, Verified>> = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(new URL("../src/lib/ctxVerified.ts", import.meta.url), body);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, Object.keys(v).length])));
