// Builds src/lib/materialIcons.ts and src/lib/iconPaths.ts from the official Material Symbols Rounded SVGs
// (npm: @material-symbols/svg-400). Offline, deterministic, no icon font and no ligature fallbacks.
// Every quoted token in src/ that is a real Material Symbol name is bundled, so a name can never render as text.
// Extra names that are built dynamically can be listed in a `/* icons: a, b */` comment.
// Usage: node scripts/icons.mjs
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = "node_modules/@material-symbols/svg-400/rounded";
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const extra = "scripts/extra-icons"; // icons absent from the npm package, cached from fonts.gstatic.com
const available = new Set([...readdirSync(root), ...readdirSync(extra)].filter((f) => f.endsWith(".svg") && !f.endsWith("-fill.svg")).map((f) => f.slice(0, -4)));

// Fetch (and cache) names the npm package lacks; the Google CDN always has them.
const wanted = new Set();
for (const f of walk("src").filter((f) => /\.(tsx?|css)$/.test(f) && !/materialIcons|iconPaths/.test(f)))
  for (const m of readFileSync(f, "utf8").matchAll(/(?:<Icon\s+name\s*=\s*\{?|\bicon[A-Za-z]*\s*[:=]\s*\{?|\bi\s*:|\bic\()\s*[{(]?\s*["']([a-z][a-z0-9_]+)["']/g)) wanted.add(m[1]);
for (const f of walk("src").filter((f) => /\.(tsx?|css)$/.test(f) && !/materialIcons|iconPaths/.test(f)))
  for (const m of readFileSync(f, "utf8").matchAll(/\/\*\s*icons:\s*([a-z0-9_,\s]+)\*\//g)) m[1].split(/[,\s]+/).filter(Boolean).forEach((n) => wanted.add(n));
for (const n of wanted) {
  if (available.has(n)) continue;
  for (const [suffix, variant] of [["", "default"], ["-fill", "fill1"]]) {
    try {
      const r = await fetch(`https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/${n}/${variant}/24px.svg`);
      if (r.ok) writeFileSync(`${extra}/${n}${suffix}.svg`, await r.text());
    } catch { /* offline: handled by the missing-icon report */ }
  }
  if (existsSync(`${extra}/${n}.svg`)) available.add(n);
  else console.error("UNRESOLVED explicit icon:", n);
}
for (const n of wanted) if (!available.has(n)) process.exitCode = 1;
for (const n of wanted) available.has(n) && 0;
const names = new Set(wanted);
const screenNames = new Set();
for (const f of walk("src").filter((f) => /\.(tsx?|css)$/.test(f) && !/materialIcons|iconPaths/.test(f))) {
  const s = readFileSync(f, "utf8");
  for (const m of s.matchAll(/["'`]([a-z][a-z0-9_]{1,40})["'`]/g)) if (available.has(m[1])) names.add(m[1]);
  for (const m of s.matchAll(/\/\*\s*icons:\s*([a-z0-9_,\s]+)\*\//g)) m[1].split(/[,\s]+/).filter(Boolean).forEach((n) => names.add(n));
  for (const m of s.matchAll(/@@([a-z0-9_]+)@@/g)) { names.add(m[1]); screenNames.add(m[1]); }
}
const pathOf = (file) => { const f = existsSync(file) ? file : file.replace(root, extra); return existsSync(f) ? /<path d="([^"]+)"/.exec(readFileSync(f, "utf8"))?.[1] ?? "" : ""; };
const out = {};
const missing = [];
for (const n of [...names].sort()) {
  const o = pathOf(`${root}/${n}.svg`);
  if (!o) { missing.push(n); continue; }
  const f = pathOf(`${root}/${n}-fill.svg`);
  out[n] = f && f !== o ? [o, f] : [o];
}
if (missing.length) console.error("missing icons:", missing.join(", "));
writeFileSync("src/lib/materialIcons.ts", `// Generated by scripts/icons.mjs from @material-symbols/svg-400 (rounded). Do not edit.\n// name -> [outlined path, filled path?] on a 0 -960 960 960 viewBox.\nexport const MATERIAL_ICONS: Record<string, string[]> = ${JSON.stringify(out)};\n`);
const screens = {};
for (const n of [...screenNames].sort()) if (out[n]) screens[n] = out[n][0];
writeFileSync("src/lib/iconPaths.ts", `// Generated by scripts/icons.mjs. Do not edit.\nexport const ICON_PATHS: Record<string, string> = ${JSON.stringify(screens, null, 1)};\n`);
console.log(Object.keys(out).length, "icons,", Object.keys(screens).length, "screen icons");
