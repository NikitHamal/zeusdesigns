// Builds src/lib/iconPaths.ts: Material Symbols Rounded SVG paths used by generated demo screens.
// Screens render inside sandboxed iframes, so they inline SVG instead of using the icon font.
// Usage: node scripts/screen-icons.mjs (needs network)
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/lib/templates.ts", "utf8");
const names = [...new Set([...src.matchAll(/@@([a-z0-9_]+)@@/g)].map((m) => m[1]))].sort();
const out = {};
for (const n of names) {
  const r = await fetch(`https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/${n}/default/24px.svg`);
  if (!r.ok) { console.error("missing icon", n, r.status); continue; }
  out[n] = /<path d="([^"]+)"/.exec(await r.text())?.[1] ?? "";
}
writeFileSync("src/lib/iconPaths.ts", `// Generated by scripts/screen-icons.mjs. Do not edit.\nexport const ICON_PATHS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, "of", names.length);
